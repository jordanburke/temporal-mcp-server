#!/usr/bin/env node
// Keeps src/version.ts in step with package.json.
//
// The server reports its version over the wire (`info`, `initialize`), and that
// string used to be hand-maintained in src/index.ts — so a release could ship a
// package labelled 0.2.1 that introduced itself to clients as 0.2.0.
//
// package.json cannot simply be imported: tsconfig sets rootDir to src, so a
// `../package.json` import is out of the compilation root. Generating a module
// avoids that, and avoids defining the value separately for tsdown, vitest, and
// wrangler (which bundles src/worker.ts with its own esbuild).
//
//   node scripts/sync-version.mjs           write src/version.ts
//   node scripts/sync-version.mjs --check   fail if it is stale
//
// Runs automatically via the npm `version` lifecycle, and --check runs in the
// build so a hand-edit cannot reach npm.

import { readFile, writeFile } from "node:fs/promises"

const TARGET = "src/version.ts"

const { version } = JSON.parse(await readFile("package.json", "utf8"))

const contents = `// GENERATED by scripts/sync-version.mjs — do not edit.
// Sourced from package.json; run \`pnpm sync:version\` after changing it.
export const SERVER_VERSION = "${version}"
`

const check = process.argv.includes("--check")

if (check) {
  const current = await readFile(TARGET, "utf8").catch(() => "")
  if (current !== contents) {
    console.error(`✗ ${TARGET} is out of sync with package.json (${version}).`)
    console.error("  Run: pnpm sync:version")
    process.exit(1)
  }
  console.log(`✓ ${TARGET} matches package.json (${version})`)
} else {
  await writeFile(TARGET, contents)
  console.log(`✓ wrote ${TARGET} (${version})`)
}
